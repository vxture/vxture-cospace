"""Rebuildable, scene-indexed read metadata; never an authorization source."""
from contextlib import closing
import json
from pathlib import Path
import sqlite3


class SceneReadModel:
    def __init__(self,root):
        self.root=Path(root);self.path=self.root/'scene-read-model.sqlite3'
        with closing(self.connect()) as db,db:
            db.execute('CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY,space TEXT NOT NULL,created TEXT NOT NULL)')
            db.execute('CREATE INDEX IF NOT EXISTS jobs_scene_latest ON jobs(space,created DESC,id DESC)')
            db.execute('CREATE TABLE IF NOT EXISTS summaries(space TEXT PRIMARY KEY,dependencies TEXT NOT NULL,body TEXT NOT NULL)')

    def connect(self):return sqlite3.connect(self.path,timeout=10)

    def register(self,record):
        if not record.get('space_id'):return
        with closing(self.connect()) as db,db:
            db.execute('INSERT OR REPLACE INTO jobs VALUES(?,?,?)',(record['id'],record['space_id'],record.get('created_at','')))
            db.execute('DELETE FROM summaries WHERE space=?',(record['space_id'],))

    def rebuild(self,records):
        # Startup reconciliation repairs a crash between atomic file save and index update.
        with closing(self.connect()) as db,db:
            db.execute('DELETE FROM jobs');db.execute('DELETE FROM summaries')
            db.executemany('INSERT INTO jobs VALUES(?,?,?)',[(r['id'],r['space_id'],r.get('created_at','')) for r in records if r.get('space_id')])

    def latest(self,space):
        with closing(self.connect()) as db:
            row=db.execute('SELECT id FROM jobs WHERE space=? ORDER BY created DESC,id DESC LIMIT 1',(space,)).fetchone()
            return row[0] if row else None

    def fingerprint(self,paths):
        result={}
        for path in paths:
            path=Path(path);relative=path.relative_to(self.root).as_posix()
            try:
                stat=path.stat();result[relative]=[stat.st_mtime_ns,stat.st_ctime_ns,stat.st_size,stat.st_ino]
            except FileNotFoundError:result[relative]=None
        return result

    def cached(self,space,ownership):
        with closing(self.connect()) as db:
            row=db.execute('SELECT dependencies,body FROM summaries WHERE space=?',(space,)).fetchone()
        if not row:return None
        dependencies=json.loads(row[0])
        # Paths are generated by this service, never supplied by callers.
        if any(Path(name).is_absolute() or '..' in Path(name).parts for name in dependencies):return None
        saved=json.loads(row[1])
        if saved.get('ownership')!=ownership:return None
        return saved['value'] if self.fingerprint([self.root/name for name in dependencies])==dependencies else None

    def save(self,space,dependencies,body,ownership):
        with closing(self.connect()) as db,db:
            db.execute('INSERT OR REPLACE INTO summaries VALUES(?,?,?)',(space,json.dumps(dependencies),json.dumps({'ownership':ownership,'value':body})))
